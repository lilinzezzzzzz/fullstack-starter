@pytest.fixture(params=["baseline", "existing_revision"])
def migration_tree(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    request: pytest.FixtureRequest,
) -> Path:
    backend = tmp_path / "backend"
    directory = backend / "migrations"
    versions = directory / "versions"
    versions.mkdir(parents=True)
    shutil.copy2(BACKEND_ROOT / "alembic.ini", backend / "alembic.ini")
    for filename in ("env.py", "script.py.mako"):
        shutil.copy2(BACKEND_ROOT / "migrations" / filename, directory / filename)
    (versions / "baseline.py").write_text(
        f"revision = {TEST_BASELINE_REVISION!r}\ndown_revision = None\n"
        "def upgrade():\n    pass\ndef downgrade():\n    pass\n"
    )
    metadata = MetaData(naming_convention=Base.metadata.naming_convention)
    if request.param == "existing_revision":
        Table("migration_history_probe", metadata, Column("id", Integer, primary_key=True))
        (versions / "existing.py").write_text(
            dedent(f"""\
            import sqlalchemy as sa
            from alembic import op

            revision = "test_existing"
            down_revision = {TEST_BASELINE_REVISION!r}

            def upgrade():
                op.create_table(
                    "migration_history_probe",
                    sa.Column("id", sa.Integer(), nullable=False),
                    sa.PrimaryKeyConstraint("id", name="pk_migration_history_probe"),
                )

            def downgrade():
                op.drop_table("migration_history_probe")
            """)
        )
    monkeypatch.setattr(operations, "BACKEND_ROOT", backend)
    monkeypatch.setattr(Base, "metadata", metadata)
    return directory


