@pytest.mark.parametrize("operation", ["check", "revision"])
def test_multiple_heads_are_rejected_before_replay_or_generation(
    migration_settings: Settings,
    migration_tree: Path,
    operation: str,
) -> None:
    (migration_tree / "versions" / "other_head.py").write_text(
        'revision = "other_head"\ndown_revision = None\n'
        "def upgrade():\n    pass\ndef downgrade():\n    pass\n"
    )
    before = set((migration_tree / "versions").glob("*.py"))
    migrations = DatabaseMigrations(migration_settings)
    with pytest.raises(CommandError, match="exactly one Alembic head"):
        if operation == "check":
            migrations.check()
        else:
            migrations.create_revision("must not be generated")
    assert list(migration_settings.testing.temporary_directory.iterdir()) == []
    assert set((migration_tree / "versions").glob("*.py")) == before


def test_failed_replay_cleans_temporary_database_without_creating_a_revision(
    migration_settings: Settings,
    migration_tree: Path,
) -> None:
    previous_head = ScriptDirectory.from_config(
        migration_config(migration_settings),
    ).get_current_head()
    (migration_tree / "versions" / "broken.py").write_text(
        f'revision = "broken"\ndown_revision = {previous_head!r}\n'
        'def upgrade():\n    raise RuntimeError("broken migration probe")\n'
        "def downgrade():\n    pass\n"
    )
    before = set((migration_tree / "versions").glob("*.py"))
    with pytest.raises(RuntimeError, match="broken migration probe"):
        DatabaseMigrations(migration_settings).create_revision("must not be generated")
    assert set((migration_tree / "versions").glob("*.py")) == before
    assert not migration_settings.data_dir.exists()
    assert list(migration_settings.testing.temporary_directory.iterdir()) == []


