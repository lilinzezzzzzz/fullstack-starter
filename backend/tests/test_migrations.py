@pytest.mark.parametrize("empty", [False, True])
def test_revision_cli_supports_autogeneration_and_manual_revisions(
    migration_settings: Settings,
    migration_tree: Path,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    empty: bool,
) -> None:
    before = set((migration_tree / "versions").glob("*.py"))
    arguments = [
        "app.cli",
        "--config",
        str(tmp_path / "settings.toml"),
        "db-revision",
        "--message",
        "manual data change" if empty else "no model changes",
    ]
    if empty:
        arguments.append("--empty")
    monkeypatch.setattr(sys, "argv", arguments)
    cli.main()
    output = capsys.readouterr()
    assert ("Candidate migration:" if empty else "no revision created") in output.out
    after = set((migration_tree / "versions").glob("*.py"))
    assert before <= after
    assert len(after - before) == int(empty)


