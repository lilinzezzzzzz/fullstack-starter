def test_reviewed_batch_rename_and_backfill_preserve_existing_records(
    migration_settings: Settings,
    migration_tree: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    previous = MetaData()
    Table(
        "migration_probe",
        previous,
        Column("id", Integer, primary_key=True),
        Column("name", Text, nullable=True),
    )
    monkeypatch.setattr(Base, "metadata", previous)
    migrations = DatabaseMigrations(migration_settings)
    assert migrations.create_revision("create migration probe") is not None
    upgrade_database(migration_settings)
    with closing(sqlite3.connect(migration_settings.database_path, autocommit=True)) as connection:
        connection.execute("INSERT INTO migration_probe VALUES (1, 'keep me'), (2, NULL)")

    current = MetaData()
    Table(
        "migration_probe",
        current,
        Column("id", Integer, primary_key=True),
        Column("display_name", Text, nullable=False),
    )
    monkeypatch.setattr(Base, "metadata", current)
    generated = migrations.create_revision("rename and backfill probe name")
    assert generated is not None
    candidate = generated.read_text()
    assert "add_column" in candidate and "drop_column" in candidate
    script = ScriptDirectory.from_config(migration_config(migration_settings)).get_revision("head")
    assert script is not None
    generated.write_text(
        dedent(f"""\
        import sqlalchemy as sa
        from alembic import op

        revision = {script.revision!r}
        down_revision = {script.down_revision!r}

        def upgrade():
            with op.batch_alter_table("migration_probe") as batch:
                batch.alter_column(
                    "name",
                    new_column_name="display_name",
                    existing_type=sa.Text(),
                )
            op.execute(
                "UPDATE migration_probe SET display_name = 'unknown' "
                "WHERE display_name IS NULL"
            )
            with op.batch_alter_table("migration_probe") as batch:
                batch.alter_column("display_name", existing_type=sa.Text(), nullable=False)

        def downgrade():
            raise RuntimeError("Backfill is lossy; restore a verified pre-upgrade snapshot.")
        """)
    )

    migrations.check()
    upgrade_database(migration_settings)
    upgrade_database(migration_settings)
    assert isinstance(script.down_revision, str)
    with pytest.raises(RuntimeError, match="Backfill is lossy"):
        command.downgrade(migration_config(migration_settings), script.down_revision)

    with closing(sqlite3.connect(migration_settings.database_path, autocommit=True)) as connection:
        assert connection.execute(
            "SELECT id, display_name FROM migration_probe ORDER BY id"
        ).fetchall() == [(1, "keep me"), (2, "unknown")]
        with pytest.raises(sqlite3.IntegrityError):
            connection.execute("INSERT INTO migration_probe VALUES (3, NULL)")
        assert connection.execute("PRAGMA integrity_check").fetchone() == ("ok",)
        assert connection.execute("SELECT version_num FROM alembic_version").fetchone() == (
            script.revision,
        )
